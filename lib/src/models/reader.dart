class QuoteReader {
  final int? id;
  final String name;
  final DateTime createdAt;

  QuoteReader({
    this.id,
    required this.name,
    required this.createdAt,
  });

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'name': name,
      'created_at': createdAt.toIso8601String(),
    };
  }

  factory QuoteReader.fromMap(Map<String, dynamic> map) {
    return QuoteReader(
      id: map['id'] as int?,
      name: map['name'] as String,
      createdAt: DateTime.parse(map['created_at'] as String),
    );
  }
}
